"""Encoding using one hot codding"""

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder
from sklearn.ensemble import RandomForestClassifier
from sklearn.pipeline import Pipeline
from sklearn.metrics import accuracy_score, f1_score, classification_report, confusion_matrix

preprocessor = ColumnTransformer(
    transformers=[("cat", OneHotEncoder(handle_unknown="ignore"), categorical_features)],
    remainder="passthrough"  # numeric_features pass through as-is
)

"""Random Forest model"""

clf_pipeline = Pipeline([
    ("prep", preprocessor),
    ("model", RandomForestClassifier(
        n_estimators=200,
        max_depth=16,
        class_weight="balanced_subsample",  # Preventive rows outnumber Corrective ~8:1
        random_state=42,
        n_jobs=-1,
    )),
])

clf_pipeline.fit(X_train, y_train_type)

"""Prediction and Evaluation"""

y_pred_type = clf_pipeline.predict(X_test)

print("Accuracy:", accuracy_score(y_test_type, y_pred_type))
print("Macro F1:", f1_score(y_test_type, y_pred_type, average="macro"))
print()
print(classification_report(y_test_type, y_pred_type, zero_division=0))
print("Confusion matrix (rows=actual, cols=predicted):")
print(confusion_matrix(y_test_type, y_pred_type, labels=["Corrective", "Predictive", "Preventive"]))

"""Train the regression"""

from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
import numpy as np

def train_and_evaluate_regressor(y_train, y_test, target_name):
    pipeline = Pipeline([
        ("prep", preprocessor),
        ("model", RandomForestRegressor(n_estimators=200, max_depth=16, random_state=42, n_jobs=-1)),
    ])
    pipeline.fit(X_train, y_train)
    y_pred = pipeline.predict(X_test)

    mae = mean_absolute_error(y_test, y_pred)
    rmse = np.sqrt(mean_squared_error(y_test, y_pred))
    r2 = r2_score(y_test, y_pred)

    print(f"--- {target_name} ---")
    print(f"MAE: {mae:.4f}   RMSE: {rmse:.4f}   R2: {r2:.4f}\n")
    return pipeline, y_pred

risk_pipeline, risk_pred = train_and_evaluate_regressor(y_train_risk, y_test_risk, "failure_risk_score")
rul_pipeline, rul_pred   = train_and_evaluate_regressor(y_train_rul,  y_test_rul,  "remaining_useful_life_days")
due_pipeline, due_pred   = train_and_evaluate_regressor(y_train_due,  y_test_due,  "days_until_due")

