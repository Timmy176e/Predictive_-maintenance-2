import matplotlib.pyplot as plt

def plot_feature_importance(pipeline, title, top_n=8):
    feature_names = pipeline.named_steps["prep"].get_feature_names_out()
    feature_names = [n.replace("cat__", "").replace("remainder__", "") for n in feature_names]
    importances = pipeline.named_steps["model"].feature_importances_

    order = np.argsort(importances)[::-1][:top_n]
    plt.figure(figsize=(7, 4))
    plt.barh([feature_names[i] for i in order][::-1], [importances[i] for i in order][::-1])
    plt.title(title)
    plt.xlabel("Importance")
    plt.tight_layout()
    plt.show()

plot_feature_importance(clf_pipeline, "What drives maintenance-type predictions")
